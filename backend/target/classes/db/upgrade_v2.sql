    rotation_cycle INT DEFAULT 7 COMMENT '轮换周期(天)',
    weekend_staff_boost INT DEFAULT 0 COMMENT '周末增加人数',
    holiday_staff_boost INT DEFAULT 0 COMMENT '节假日增加人数',
