-- 排班计划表（周期排班）
CREATE TABLE IF NOT EXISTS schedule_plan (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    plan_no VARCHAR(64) NOT NULL COMMENT '排班编号',
    plan_name VARCHAR(64) NOT NULL COMMENT '排班名称',
    position_type VARCHAR(32) NOT NULL COMMENT '岗位类型',
    schedule_type VARCHAR(32) DEFAULT 'WEEKLY' COMMENT '排班周期类型 WEEKLY-周排班 MONTHLY-月排班 CUSTOM-自定义',
    start_date DATE NOT NULL COMMENT '排班开始日期',
    end_date DATE NOT NULL COMMENT '排班结束日期',
    total_shifts INT DEFAULT 0 COMMENT '总班次数',
    total_staff INT DEFAULT 0 COMMENT '涉及员工数',
    plan_status TINYINT DEFAULT 0 COMMENT '排班状态 0-草稿 1-已发布 2-已作废',
    publish_time DATETIME COMMENT '发布时间',
