-- 员工技能标签表
CREATE TABLE IF NOT EXISTS employee_skill (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    employee_id BIGINT NOT NULL COMMENT '员工ID',
    skill_code VARCHAR(32) NOT NULL COMMENT '技能编码 LIFEGUARD-救生员 COACH-教练 OPERATION-运维 FRONT_DESK-前台 CLEANER-保洁',
    skill_name VARCHAR(64) NOT NULL COMMENT '技能名称',
    skill_level TINYINT DEFAULT 1 COMMENT '技能等级 1-初级 2-中级 3-高级 4-专家',
    cert_no VARCHAR(64) COMMENT '证书编号',
    cert_expire_date DATE COMMENT '证书到期日',
    create_time DATETIME COMMENT '创建时间',
    update_time DATETIME COMMENT '更新时间',
    create_by BIGINT COMMENT '创建人',
    update_by BIGINT COMMENT '更新人',
    deleted TINYINT DEFAULT 0 COMMENT '删除标记',
    KEY idx_employee_id (employee_id),
    KEY idx_skill_code (skill_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='员工技能标签表';

-- 班次模板表
CREATE TABLE IF NOT EXISTS shift_template (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    shift_name VARCHAR(64) NOT NULL COMMENT '班次名称',
    shift_code VARCHAR(32) NOT NULL COMMENT '班次编码 MORNING-早班 MIDDLE-中班 EVENING-晚班 NIGHT-夜班',
