    update_by BIGINT COMMENT '更新人',
    deleted TINYINT DEFAULT 0 COMMENT '删除标记',
    KEY idx_position_type (position_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='排班规则配置表';

-- 员工排班偏好表
